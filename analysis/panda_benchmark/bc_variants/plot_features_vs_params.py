"""Relation between inlet integral measures and first-cell closure.

Two colours are used in the controlled 2D set: the wall-attached family and the
shifted-tanh family with a = 170 um and s = 3--7. The latter holds theta_c and
delta_omega fixed while varying delta*_c. The top hat is drawn separately
because it belongs to neither family. Every 2D value is taken from the L4
calculation with a finest spacing of D_e/256.

The 3D values are read from ``shockcell_marks.npz``, which is generated by
``extract_profile_density_features.py`` using the density-based definition in
Section 3.4.  The 2D values use the same closure extraction on the L4 sweep.
"""
